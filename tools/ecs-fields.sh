#!/usr/bin/env bash
# Regenerates src/io/ecs_fields.rs from ECS's published field list. Usage: tools/ecs-fields.sh 9.5.0
set -euo pipefail
version="$1"
url="https://raw.githubusercontent.com/elastic/ecs/v${version}/generated/csv/fields.csv"
out="$(dirname "$0")/../src/io/ecs_fields.rs"

rows="$(curl -sSfL "$url" | awk -F, -v version="$version" '
  # A row starts with the version; any other line continues a multi-line example.
  $1 != version { next }
  { indexed[$4] = $2; type[$4] = $5; order[n++] = $4 }
  END {
    split("boolean:Boolean constant_keyword:ConstantKeyword date:Date double:Double flattened:Flattened float:Float geo_point:GeoPoint ip:Ip long:Long nested:Nested object:Object scaled_float:ScaledFloat", pairs, " ")
    for (p in pairs) { split(pairs[p], kv, ":"); plain[kv[1]] = kv[2] }
    for (i = 0; i < n; i++) {
      f = order[i]; t = type[f]
      # A `.text` row under a string field is that field'"'"'s text sub-field, not a field of its own.
      parent = f; sub(/\.text$/, "", parent)
      if (parent != f && (type[parent] == "keyword" || type[parent] == "wildcard")) continue
      text = (type[f ".text"] == "match_only_text")
      shape = ""
      if (indexed[f] == "false") {
        if (t == "keyword") shape = "Unindexed"
        else if (t == "long") shape = "UnindexedLong"
      }
      else if (t == "keyword") shape = text ? "KeywordText" : "Keyword"
      else if (t == "wildcard") shape = text ? "WildcardText" : "Wildcard"
      else if (t == "match_only_text") shape = "MatchOnlyText"
      # `elastic_mapping` gives each scaled float the factor ECS gives these: one more must be checked by hand.
      else if (t == "scaled_float" && f !~ /^(container|host|host\.target)\.(cpu|memory)\.usage$/) { print "ecs-fields.sh: check the scaling factor of " f > "/dev/stderr"; exit 1 }
      else shape = plain[t]
      if (shape == "") { print "ecs-fields.sh: no shape for " f ", a " t (indexed[f] == "false" ? " not indexed" : "") > "/dev/stderr"; exit 1 }
      print "    (\"" f "\", Ecs::" shape "),"
    }
  }' | LC_ALL=C sort)"

cat > "$out" <<RS
//! Every ECS field and how ECS maps it, from ECS ${version}.
//! Generated by \`tools/ecs-fields.sh ${version}\` from ${url}; do not edit by hand.

use crate::io::elastic_mapping::Ecs;

pub const ECS_VERSION: &str = "${version}";

/// By full dotted name, in byte order.
pub const FIELDS: &[(&str, Ecs)] = &[
${rows}
];
RS
