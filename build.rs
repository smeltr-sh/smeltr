//! Bakes `gui-frontend/dist` into the binary, so one file copied to a host serves the GUI.
//!
//! A generated table rather than `rust-embed`: `dist` is a build artifact, absent on a fresh clone, and deliberately
//! not a dependency of the Rust build, so the missing case has to be handled here either way. When it is missing or
//! empty, the table holds one `index.html` that says so.

use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::{SystemTime, UNIX_EPOCH};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let dist = manifest.join("gui-frontend/dist");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("embedded_assets.rs");

    // `just check` builds the GUI on its own, beside this build, so its binary embeds the placeholder and says nothing.
    println!("cargo:rerun-if-env-changed=SMELTR_NO_GUI");
    // A checkout that shares `target/` with another would otherwise take the other's build as fresh: cargo keys this
    // crate's build by file times, not by where its sources are. `.cargo/config.toml` sets it per checkout.
    println!("cargo:rerun-if-env-changed=SMELTR_CHECKOUT");
    let no_gui = std::env::var("SMELTR_NO_GUI").is_ok_and(|v| !v.is_empty());

    // Vite content-hashes its output names, so watching the directory is what catches a rename. The sources are watched
    // for the staleness check. `dist` is made empty when absent, since only a path that exists can be watched: the
    // bundler's first build is then a change to a directory already watched. A build without the GUI watches none of
    // it, so a GUI edit does not rebuild the crate for the tests and clippy.
    let _ = std::fs::create_dir(&dist);
    if !no_gui {
        for watched in ["dist", "src", "public", "index.html", "package.json"] {
            watch(&manifest.join("gui-frontend").join(watched));
        }
        for watched in [
            "website/src/lib/highlight",
            "website/src/lib/foundry",
            "website/src/lib/reference.json",
            "website/src/lib/code-language.json",
            "website/src/lib/signatures.json",
        ] {
            watch(&manifest.join(watched));
        }
        warn_if_stale(&manifest, &dist);
    }
    let edits = uncommitted(&manifest);
    println!("cargo:rustc-env=SMELTR_VERSION={}", compute_version(&manifest, &edits));
    println!("cargo:rustc-env=SMELTR_RELEASE={}", release(&manifest, &edits));

    let mut files = Vec::new();
    if !no_gui {
        collect(&dist, &dist, &mut files);
    }
    files.sort();

    let mut src = String::from(
        "// Generated by build.rs. `(request path, bytes)`, sorted.\n\
         pub static ASSETS: &[(&str, &[u8])] = &[\n",
    );
    if files.is_empty() {
        src.push_str(&format!("    (\"index.html\", {:?}.as_bytes()),\n", PLACEHOLDER_HTML));
        if !no_gui {
            println!(
                "cargo:warning=gui-frontend/dist is empty or missing, so this binary has no GUI \
                 baked in -- it will serve a page saying so. Run `npm ci && npm run build` in \
                 gui-frontend and rebuild."
            );
        }
    }
    for rel in &files {
        let abs = dist.join(rel);
        src.push_str(&format!(
            "    ({:?}, include_bytes!({:?})),\n",
            rel.replace('\\', "/"),
            abs
        ));
    }
    src.push_str("];\n");

    std::fs::write(&out, src).expect("write embedded_assets.rs");
}

/// `dist` older than the frontend sources is an error on a release build and a warning otherwise. `cargo build` does
/// not run the bundler: that would put node on the path of every `cargo check`, and a script that writes to a path it
/// watches rebuilds forever. A stale GUI is silent where a missing one announces itself, which is why only staleness is
/// promoted on release. `SMELTR_ALLOW_STALE_GUI=1` keeps it a warning.
fn warn_if_stale(manifest: &Path, dist: &Path) {
    println!("cargo:rerun-if-env-changed=SMELTR_ALLOW_STALE_GUI");

    let Some(built) = newest_mtime(dist) else {
        return; // nothing built into dist: the empty-table branch already warns
    };
    let sources = [
        manifest.join("gui-frontend/src"),
        manifest.join("gui-frontend/public"),
        manifest.join("gui-frontend/index.html"),
        manifest.join("gui-frontend/package.json"),
        manifest.join("website/src/lib/highlight"),
        manifest.join("website/src/lib/foundry"),
    ];
    let Some(edited) = sources.iter().filter_map(|p| newest_mtime(p)).max() else {
        return; // no sources to compare against (a packaged source tree)
    };
    if edited <= built {
        return;
    }

    let release = std::env::var("PROFILE").as_deref() == Ok("release");
    let overridden = std::env::var("SMELTR_ALLOW_STALE_GUI").is_ok_and(|v| !v.is_empty());
    if release && !overridden {
        panic!(
            "gui-frontend/dist is older than gui-frontend's sources, so this release binary \
             would embed the PREVIOUS frontend build.\n\
             \n\
             Build both, in order:    just build\n\
             Or by hand:              (cd gui-frontend && npm run build) && cargo build --release\n\
             \n\
             Set SMELTR_ALLOW_STALE_GUI=1 to build anyway (profiling, benchmarks -- anything \
             that does not care about the UI). A debug build only warns."
        );
    }
    println!(
        "cargo:warning=gui-frontend/dist is older than gui-frontend's sources, so this binary \
         will embed the PREVIOUS frontend build. Run `just build-dev`, or `npm run build` in \
         gui-frontend and build again. (cargo does not run the bundler for you -- see build.rs.) \
         A release build refuses outright rather than warning."
    );
}

/// `2026.9.20+main.1244c9e5a0b3`: the compile date as three semver-shaped numbers, and which commit on which
/// branch built it as semver's own build metadata. Two builds on the same day differ only in the
/// metadata, which sorts nowhere -- telling them apart, not ranking them, is what it is for.
///
/// A build that cannot read its commit fails: a worker takes deployments only from a leader built from the same
/// commit, so a build that cannot say which one it is could never be given one. A build with uncommitted edits to
/// what it is made from names them too (`1244c9e5a0b3-dirty-3f0a9c1d2e4b`), so two builds with different edits
/// on one commit are two builds.
fn compute_version(manifest: &Path, edits: &str) -> String {
    watch_git_refs(manifest);
    let (year, month, day) = civil_from_days(days_since_epoch());
    let branch = git(manifest, &["symbolic-ref", "--short", "-q", "HEAD"])
        .map(|b| sanitize(&b))
        .unwrap_or_else(|| "detached".to_string());
    let Some(sha) = git(manifest, &["rev-parse", "HEAD"]) else {
        panic!(
            "smeltr builds from a git checkout: `git rev-parse HEAD` found no commit in {}",
            manifest.display()
        );
    };
    // Cut here rather than by `--short`, which lengthens an abbreviation that is ambiguous in that clone: two
    // clones of one commit would name it differently, and a leader would refuse a worker built from it.
    let sha = &sha[..sha.len().min(12)];
    format!("{year}.{month}.{day}+{branch}.{sha}{edits}")
}

/// `1.2.0` when the commit carries the tag `v1.2.0` and nothing uncommitted is built in, else empty: an edited
/// build is not the release, whatever commit it sits on. A tag that is not semver (`v1-old`) names no release.
fn release(manifest: &Path, edits: &str) -> String {
    if !edits.is_empty() {
        return String::new();
    }
    git(
        manifest,
        &["describe", "--exact-match", "--tags", "--match", "v[0-9]*", "HEAD"],
    )
    .and_then(|tag| tag.strip_prefix('v').map(str::to_string))
    .filter(|name| is_semver(name))
    .unwrap_or_default()
}

/// `major.minor.patch`, optionally `-` and a pre-release of ASCII alphanumerics, dots and hyphens.
fn is_semver(name: &str) -> bool {
    let (core, pre) = name.split_once('-').unwrap_or((name, "a"));
    let numbers: Vec<&str> = core.split('.').collect();
    numbers.len() == 3
        && numbers
            .iter()
            .all(|n| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()))
        && !pre.is_empty()
        && pre.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'.' || b == b'-')
}

/// What a build is made from: an edit under any of these is in the binary.
const SOURCES: [&str; 4] = ["src", "build.rs", "Cargo.toml", "Cargo.lock"];

/// `-dirty-` and the first 12 of a hash of every uncommitted edit to [`SOURCES`], or nothing when there is none.
/// Git hashes it, so builds on any platform name the same edits the same way.
fn uncommitted(manifest: &Path) -> String {
    for source in SOURCES {
        watch(&manifest.join(source));
    }
    let diff = git(
        manifest,
        &[&["diff", "HEAD", "--binary", "--"][..], &SOURCES[..]].concat(),
    );
    let untracked = git(
        manifest,
        &[&["ls-files", "--others", "--exclude-standard", "--"][..], &SOURCES[..]].concat(),
    );
    if diff.is_none() && untracked.is_none() {
        return String::new();
    }
    let mut edits = diff.unwrap_or_default().into_bytes();
    for file in untracked.iter().flat_map(|files| files.lines()) {
        edits.extend(file.as_bytes());
        edits.extend(std::fs::read(manifest.join(file)).unwrap_or_default());
    }
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("uncommitted-edits");
    std::fs::write(&out, edits).unwrap();
    let hash = git(manifest, &["hash-object", &out.to_string_lossy()])
        .expect("git hashes the uncommitted edits it just listed");
    format!("-dirty-{}", &hash[..hash.len().min(12)])
}

/// Semver build metadata is dot-separated groups of ASCII alphanumerics and hyphens; a branch name's `/`
/// is not one, so it becomes a hyphen rather than a second dot -- a dot would turn one identifier into two.
fn sanitize(branch: &str) -> String {
    branch
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '-' { c } else { '-' })
        .collect()
}

/// `HEAD` names a branch rather than holding a commit, so an ordinary commit on that branch never
/// touches it -- cargo would keep the version from whichever build first ran this script. What actually
/// moves is the branch's ref: a file under `refs/heads`, or a line in `packed-refs` once it is packed.
/// `refs/heads` is watched whole, so a ref written there for the first time is caught too, and `refs/tags`
/// likewise, so tagging the commit just built gives the next build its release name. `--git-path`
/// says where each lives; a worktree has a `HEAD` of its own.
fn watch_git_refs(manifest: &Path) {
    for name in ["HEAD", "packed-refs", "refs/heads", "refs/tags"] {
        if let Some(path) = git(manifest, &["rev-parse", "--git-path", name]) {
            watch(&manifest.join(path));
        }
    }
}

/// Watch `path` for changes, if it exists. Cargo reads a watched path it cannot find as changed on every
/// build, which reruns this script and rebuilds the crate each time.
fn watch(path: &Path) {
    if path.exists() {
        println!("cargo:rerun-if-changed={}", path.display());
    }
}

/// `GIT_CEILING_DIRECTORIES` keeps discovery inside `manifest`: without it, a checkout with no `.git` of
/// its own -- a source tarball extracted under an unrelated repository -- would have git walk up and
/// report that outer repository's branch and commit instead of falling back to "unknown".
fn git(manifest: &Path, args: &[&str]) -> Option<String> {
    let ceiling = manifest.parent().unwrap_or(manifest);
    let output = Command::new("git")
        .args(args)
        .current_dir(manifest)
        .env("GIT_CEILING_DIRECTORIES", ceiling)
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let text = String::from_utf8(output.stdout).ok()?;
    let text = text.trim();
    if text.is_empty() { None } else { Some(text.to_string()) }
}

fn days_since_epoch() -> i64 {
    SystemTime::now().duration_since(UNIX_EPOCH).unwrap().as_secs() as i64 / 86_400
}

/// Days since the Unix epoch to a (year, month, day) in UTC. Howard Hinnant's `civil_from_days`, exact
/// over the whole proleptic Gregorian calendar, so one date needs no calendar crate as a build dependency.
fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = (z - era * 146_097) as u64;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe as i64 + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let month = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (if month <= 2 { y + 1 } else { y }, month, day)
}

fn newest_mtime(path: &Path) -> Option<std::time::SystemTime> {
    let meta = std::fs::metadata(path).ok()?;
    if meta.is_file() {
        return meta.modified().ok();
    }
    let mut newest = None;
    for entry in std::fs::read_dir(path).ok()?.flatten() {
        if let Some(t) = newest_mtime(&entry.path()) {
            newest = Some(newest.map_or(t, |n: std::time::SystemTime| n.max(t)));
        }
    }
    newest
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return; // missing dist: handled by the empty-table branch above
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if let Ok(rel) = path.strip_prefix(root) {
            out.push(rel.to_string_lossy().into_owned());
        }
    }
}

